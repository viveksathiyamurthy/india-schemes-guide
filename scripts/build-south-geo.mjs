/**
 * Builds src/data/southGeo.ts: simplified [lon, lat] outlines of the five southern states,
 * taken from src/data/geoData.ts. Screen 1 draws them over the satellite globe.
 * Usage: node scripts/build-south-geo.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';

const SLUGS = ['tamil-nadu', 'kerala', 'karnataka', 'andhra-pradesh', 'telangana'];
const TOL = 0.01; // degrees, about 1 km

const src = readFileSync(new URL('../src/data/geoData.ts', import.meta.url), 'utf8');
const all = JSON.parse(src.slice(src.indexOf('= {') + 2, src.indexOf('};') + 1));

// Douglas-Peucker; a closed ring falls back to distance from its first point.
function dp(pts, tol) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = pts[a];
    const dx = pts[b][0] - ax, dy = pts[b][1] - ay;
    const len = Math.hypot(dx, dy);
    let md = 0, mi = -1;
    for (let i = a + 1; i < b; i++) {
      const d = len < 1e-6 ? Math.hypot(pts[i][0] - ax, pts[i][1] - ay) : Math.abs(dy * (pts[i][0] - ax) - dx * (pts[i][1] - ay)) / len;
      if (d > md) { md = d; mi = i; }
    }
    if (md > tol) { keep[mi] = 1; stack.push([a, mi], [mi, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const out = {};
for (const slug of SLUGS) {
  out[slug] = all[slug]
    .map((r) => {
      const pts = [];
      for (let i = 0; i < r.length; i += 2) pts.push([r[i], r[i + 1]]);
      return dp(pts, TOL).flatMap(([x, y]) => [Math.round(x * 100) / 100, Math.round(y * 100) / 100]);
    })
    .filter((r) => r.length >= 8);
}

writeFileSync(
  new URL('../src/data/southGeo.ts', import.meta.url),
  `/* Generated by scripts/build-south-geo.mjs. Do not edit by hand. */\n` +
    `/** Flat [lon, lat, lon, lat, ...] outlines of the five southern states, by slug. */\n` +
    `export const southStates: Record<string, number[][]> = ${JSON.stringify(out)};\n`,
);
console.log('wrote src/data/southGeo.ts');
