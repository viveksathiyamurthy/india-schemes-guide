/**
 * Builds src/data/schemes.ts from the "India Schemes Guide - Data" Google Sheet (tab "Schemes").
 *
 * Usage: node scripts/build-schemes.mjs <export file>
 *   The export is the tab downloaded as CSV (File > Download > Comma-separated values),
 *   or the JSON the Sheets API returns for a range ({ "values": [[...], ...] }).
 *
 * Every row is copied. The publishing rule (Active + Verified + official link) is applied
 * by the site itself (src/lib/search.ts), so rows that still need review stay hidden.
 */
import { readFileSync, writeFileSync } from 'node:fs';

/** The sheet has no short name or URL slug, so the site works them out; these keep existing pages where they were. */
const OVERRIDES = {
  3: { slug: 'pmay-urban-2' },
  6: { slug: 'kamarajar-breakfast-scheme' },
  8: { shortName: 'Mahalir Thittam (TNSRLM)', slug: 'mahalir-thittam' },
  25: { shortName: 'EWS Certificate', slug: 'ews-certificate' },
};

const LEVELS = ['State Government', 'Union/Central Government'];
const OTHER_LANGS = ['ml', 'te', 'kn'];
const LANG_FIELDS = ['name', 'summary', 'benefit', 'eligibility', 'documents', 'how_to_apply'];

function parseCsv(text) {
  const rows = [];
  let row = [], cell = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') quoted = false;
      else cell += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n') { row.push(cell); rows.push(row); row = []; cell = ''; }
    else if (c !== '\r') cell += c;
  }
  if (cell !== '' || row.length) { row.push(cell); rows.push(row); }
  return rows;
}

const file = process.argv[2];
if (!file) {
  console.error('Usage: node scripts/build-schemes.mjs <sheet export .csv or .json>');
  process.exit(1);
}
const raw = readFileSync(file, 'utf8');
const table = file.endsWith('.json') ? JSON.parse(raw).values : parseCsv(raw);
const header = table[0].map((h) => h.trim());
const col = (row, name) => (row[header.indexOf(name)] ?? '').trim();

const camel = (s) => s.replace(/_([a-z])/g, (_, c) => c.toUpperCase());
const slugify = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const schemes = [];
for (const row of table.slice(1)) {
  const id = Number(col(row, 'id'));
  if (!id) continue;
  const nameEn = col(row, 'name_en');
  const shortName = OVERRIDES[id]?.shortName ?? nameEn.split(' (')[0].trim();
  const level = col(row, 'government_level');
  if (!LEVELS.includes(level)) throw new Error(`Row ${id}: unknown government_level "${level}"`);
  const s = {
    id,
    slug: OVERRIDES[id]?.slug ?? slugify(shortName),
    shortName,
    nameEn,
    nameTa: col(row, 'name_ta'),
    level,
    state: col(row, 'state'),
    department: col(row, 'department'),
    userTypes: col(row, 'user_types').split(';').map((u) => u.trim()).filter(Boolean),
    summaryEn: col(row, 'summary_en'),
    summaryTa: col(row, 'summary_ta'),
    benefitEn: col(row, 'benefit_en'),
    benefitTa: col(row, 'benefit_ta'),
    eligibilityEn: col(row, 'eligibility_en'),
    eligibilityTa: col(row, 'eligibility_ta'),
    documentsEn: col(row, 'documents_en'),
    documentsTa: col(row, 'documents_ta'),
    howToApplyEn: col(row, 'how_to_apply_en'),
    howToApplyTa: col(row, 'how_to_apply_ta'),
    officialLink: col(row, 'official_link'),
    applyLink: col(row, 'apply_link'),
    status: col(row, 'status'),
    lastVerified: col(row, 'last_verified'),
    reviewStatus: col(row, 'review_status'),
  };
  // Malayalam, Telugu and Kannada, for when Kerala, Andhra Pradesh, Telangana and Karnataka open.
  for (const lang of OTHER_LANGS) {
    const text = {};
    for (const f of LANG_FIELDS) {
      const v = col(row, `${f}_${lang}`);
      if (v) text[camel(f)] = v;
    }
    if (Object.keys(text).length) (s.translations ??= {})[lang] = text;
  }
  schemes.push(s);
}

const slugs = new Set();
for (const s of schemes) {
  if (slugs.has(s.slug)) throw new Error(`Two rows share the page address /scheme/${s.slug}; add an override for row ${s.id}`);
  slugs.add(s.slug);
}

writeFileSync(
  new URL('../src/data/schemes.ts', import.meta.url),
  `/* Generated by scripts/build-schemes.mjs from the "India Schemes Guide - Data" Google Sheet. Do not edit by hand. */
import type { Scheme } from './types';

/**
 * Publishing rule: a scheme shows on the site only if status is Active, review status is Verified
 * and it has an official link (see src/lib/search.ts). Blank *Ta fields fall back to English.
 */
export const schemes: Scheme[] = ${JSON.stringify(schemes, null, 2)};
`,
);
console.log(`wrote ${schemes.length} schemes to src/data/schemes.ts`);
