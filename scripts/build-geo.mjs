/**
 * Builds src/data/geoData.ts: coastlines for the globe on the welcome screen.
 * Usage: node scripts/build-geo.mjs <india.geojson> <countries.geo.json>
 * Sources (both open data on GitHub):
 *  - github.com/udit-001/india-maps-data  (state outlines of India)
 *  - github.com/johan/world.geo.json      (public domain country outlines)
 * Numbers are longitude and latitude in degrees, stored flat: [lon, lat, lon, lat, ...].
 */
import { readFileSync, writeFileSync } from 'node:fs';

const [indiaPath, worldPath] = process.argv.slice(2);
const india = JSON.parse(readFileSync(indiaPath, 'utf8'));
const world = JSON.parse(readFileSync(worldPath, 'utf8'));

function dp(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [s, e] = stack.pop();
    const [x1, y1] = pts[s], [x2, y2] = pts[e];
    const dx = x2 - x1, dy = y2 - y1, len = Math.hypot(dx, dy) || 1e-9;
    let max = 0, idx = -1;
    for (let i = s + 1; i < e; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / len;
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol && idx > 0) { keep[idx] = 1; stack.push([s, idx], [idx, e]); }
  }
  return pts.filter((_, i) => keep[i]);
}
function ring(r, tol) {
  const closed = r[0][0] === r[r.length - 1][0] && r[0][1] === r[r.length - 1][1];
  const pts = closed ? r.slice(0, -1) : r;
  const mid = Math.floor(pts.length / 2);
  const out = [...dp(pts.slice(0, mid + 1), tol).slice(0, -1), ...dp([...pts.slice(mid), pts[0]], tol).slice(0, -1)];
  return out;
}
const flat = (pts) => pts.flatMap(([x, y]) => [Math.round(x * 100) / 100, Math.round(y * 100) / 100]);
const area = (r) => { let a = 0; for (let i = 0; i < r.length; i++) { const j = (i + 1) % r.length; a += r[i][0] * r[j][1] - r[j][0] * r[i][1]; } return a / 2; };

const FIVE = ['Tamil Nadu', 'Kerala', 'Karnataka', 'Andhra Pradesh', 'Telangana'];
const slug = (n) => n.toLowerCase().replace(/ /g, '-');
const states = {};
for (const name of new Set(india.features.map((f) => f.properties.st_nm))) {
  const f = india.features.find((f) => f.properties.st_nm === name && !f.properties.district);
  if (!f) continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  const rings = polys.flat().map((r) => ring(r, FIVE.includes(name) ? 0.012 : 0.05)).filter((r) => r.length > 3 && Math.abs(area(r)) > 0.0004);
  states[slug(name)] = rings.map(flat);
}
const others = [];
for (const f of world.features) {
  if (f.properties.name === 'India') continue;
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const p of polys) {
    const r = ring(p[0], 0.07);
    if (r.length > 3 && Math.abs(area(r)) > 0.05) others.push(flat(r));
  }
}
// Centre of each of the five states, from the biggest outline.
const centers = {};
for (const n of FIVE) {
  const rings = states[slug(n)].map((r) => r.reduce((acc, v, i) => (i % 2 ? (acc[acc.length - 1].push(v), acc) : (acc.push([v]), acc)), []));
  const big = rings.reduce((a, b) => (Math.abs(area(a)) > Math.abs(area(b)) ? a : b));
  let cx = 0, cy = 0, A = 0;
  for (let i = 0; i < big.length; i++) {
    const j = (i + 1) % big.length;
    const c = big[i][0] * big[j][1] - big[j][0] * big[i][1];
    A += c; cx += (big[i][0] + big[j][0]) * c; cy += (big[i][1] + big[j][1]) * c;
  }
  A /= 2;
  centers[slug(n)] = [Math.round((cx / (6 * A)) * 100) / 100, Math.round((cy / (6 * A)) * 100) / 100];
}
const ts = `/* Generated by scripts/build-geo.mjs. Do not edit by hand. */
/** Flat [lon, lat, lon, lat, ...] outlines of every Indian state, by slug. */
export const indiaStates: Record<string, number[][]> = ${JSON.stringify(states)};
/** Outlines of all other countries (coarse). */
export const otherLand: number[][] = ${JSON.stringify(others)};
/** Centre of each of the five states, [lon, lat]. */
export const stateCenters: Record<string, [number, number]> = ${JSON.stringify(centers)};
`;
writeFileSync(new URL('../src/data/geoData.ts', import.meta.url), ts);
console.log('states', Object.keys(states).length, 'other rings', others.length, 'bytes', ts.length, centers);
