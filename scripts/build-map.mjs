/**
 * Builds src/data/southMap.ts from district boundaries of the five southern states.
 * Usage: node scripts/build-map.mjs <path to india.geojson>
 * Source: github.com/udit-001/india-maps-data (district boundaries, 2011 census based).
 * The file holds one unnamed feature per state that is the outline of the whole state.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
const SLUGS = {
  'Tamil Nadu': 'tamil-nadu',
  Kerala: 'kerala',
  Karnataka: 'karnataka',
  'Andhra Pradesh': 'andhra-pradesh',
  Telangana: 'telangana',
};
const data = JSON.parse(readFileSync(src, 'utf8'));

const outlines = {};
for (const [name, slug] of Object.entries(SLUGS)) {
  // Each state has one unnamed feature in the file: the outline of the whole state.
  const f = data.features.find((f) => f.properties.st_nm === name && !f.properties.district);
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  outlines[slug] = polys.flat();
}

// Mercator, then fit to a 600 wide canvas.
const proj = ([lon, lat]) => [(lon * Math.PI) / 180, -Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360))];
let minX = 1e9, minY = 1e9, maxX = -1e9, maxY = -1e9;
const projected = {};
for (const [slug, rs] of Object.entries(outlines)) {
  projected[slug] = rs.map((r) => r.map(proj));
  for (const r of projected[slug]) for (const [x, y] of r) { minX = Math.min(minX, x); maxX = Math.max(maxX, x); minY = Math.min(minY, y); maxY = Math.max(maxY, y); }
}
const W = 600, pad = 14;
const scale = (W - pad * 2) / (maxX - minX);
const H = Math.ceil((maxY - minY) * scale + pad * 2);
const toXY = ([x, y]) => [(x - minX) * scale + pad, (y - minY) * scale + pad];

function dp(pts, tol) {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [s, e] = stack.pop();
    let max = 0, idx = -1;
    const [x1, y1] = pts[s], [x2, y2] = pts[e];
    const dx = x2 - x1, dy = y2 - y1, len = Math.hypot(dx, dy) || 1e-9;
    for (let i = s + 1; i < e; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / len;
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol && idx > 0) { keep[idx] = 1; stack.push([s, idx], [idx, e]); }
  }
  return pts.filter((_, i) => keep[i]);
}
// A ring starts and ends at the same point, so simplify its two halves separately.
function simplifyRing(r, tol) {
  const mid = Math.floor(r.length / 2);
  return [...dp(r.slice(0, mid + 1), tol).slice(0, -1), ...dp(r.slice(mid), tol)];
}
const area = (r) => { let a = 0; for (let i = 0; i < r.length - 1; i++) a += r[i][0] * r[i + 1][1] - r[i + 1][0] * r[i][1]; return a / 2; };
const f1 = (n) => (Math.round(n * 10) / 10).toString();

const result = {};
for (const [slug, rs] of Object.entries(projected)) {
  const xy = rs.map((r) => r.map(toXY)).map((r) => simplifyRing(r, 0.35)).filter((r) => Math.abs(area(r)) > 1.2 && r.length > 3);
  const d = xy.map((r) => 'M' + r.map((p) => f1(p[0]) + ' ' + f1(p[1])).join('L') + 'Z').join('');
  const all = xy.flat();
  const bbox = [Math.min(...all.map((p) => p[0])), Math.min(...all.map((p) => p[1])), Math.max(...all.map((p) => p[0])), Math.max(...all.map((p) => p[1]))].map(f1).map(Number);
  const big = xy.reduce((a, b) => (Math.abs(area(a)) > Math.abs(area(b)) ? a : b));
  let cx = 0, cy = 0, A = 0;
  for (let i = 0; i < big.length - 1; i++) {
    const c = big[i][0] * big[i + 1][1] - big[i + 1][0] * big[i][1];
    A += c; cx += (big[i][0] + big[i + 1][0]) * c; cy += (big[i][1] + big[i + 1][1]) * c;
  }
  A /= 2;
  result[slug] = { d, bbox, centroid: [Math.round(cx / (6 * A)), Math.round(cy / (6 * A))] };
  console.log(slug, 'rings', xy.length, 'chars', d.length, 'bbox', bbox.join(','));
}

const ts = `/* Generated by scripts/build-map.mjs. Do not edit by hand. */
export const mapViewBox = { width: ${W}, height: ${H} };
export const mapShapes: Record<string, { d: string; bbox: [number, number, number, number]; centroid: [number, number] }> = ${JSON.stringify(result, null, 2)};
`;
writeFileSync(new URL('../src/data/southMap.ts', import.meta.url), ts);
console.log('viewBox', W, H);
